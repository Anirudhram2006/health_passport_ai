async function seedDatabase() {
  try {
    await connectDB();
    console.log("[seed] Connected to MongoDB for medicine seeding...");

    for (const med of MEDICINE_CATALOGUE) {
      const normalizedBrandName = med.brandName.toLowerCase().replace(/[^a-z0-9]/g, "");
      const normalizedGenericName = med.genericName.toLowerCase().replace(/[^a-z0-9]/g, "");

      await Medicine.findOneAndUpdate(
        { normalizedBrandName, strength: med.strength },
        {
          ...med,
          normalizedBrandName,
          normalizedGenericName,
        },
        { upsert: true, new: true }
      );
    }

    console.log(`[seed] Successfully seeded ${MEDICINE_CATALOGUE.length} medicines into MongoDB database!`);
    await mongoose.disconnect();
    process.exit(0);
  } catch (err) {
    console.error("[seed] Error seeding medicine database:", err);
    process.exit(1);
  }
}

seedDatabase();
